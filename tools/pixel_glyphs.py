def g(*rows):
    assert len(rows) == 14 and all(len(r) == 14 for r in rows), rows
    return list(rows)


def over(base, *layers):
    """Overlay bitmaps: any '#' in a layer turns the cell on; '-' in a layer turns it off."""
    out = [list(r) for r in base]
    for layer in layers:
        for y, row in enumerate(layer):
            for x, ch in enumerate(row):
                if ch == "#":
                    out[y][x] = "#"
                elif ch == "-":
                    out[y][x] = "."
    return ["".join(r) for r in out]


